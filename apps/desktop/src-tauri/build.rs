fn main() {
    // Tauri embeds a window icon while expanding `generate_context!`. Keep a
    // tiny generated placeholder until the desktop branding task supplies the
    // production artwork.
    let icon = std::path::Path::new("icons/icon.png");
    if !icon.exists() {
        std::fs::create_dir_all(icon.parent().expect("icon parent")).expect("icon directory");
        std::fs::write(
            icon,
            [
                0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48,
                0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00,
                0x00, 0x1f, 0x15, 0xc4, 0x89, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x44, 0x41, 0x54, 0x78,
                0x9c, 0x63, 0xf8, 0xcf, 0xc0, 0xf0, 0x1f, 0x00, 0x05, 0x00, 0x01, 0xff, 0x89, 0x99,
                0x3d, 0x1d, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82,
            ],
        )
        .expect("placeholder icon");
    }

    // The bootstrap workspace does not ship application artwork yet. Avoid
    // asking tauri-build to compile a Windows resource until the bundle task
    // adds the production icon set; the desktop bundle is disabled for now.
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("windows") {
        tauri_build::build();
    }
}
